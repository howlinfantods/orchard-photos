"""Film looks, developed by the Fotufilm engine (https://fotufilm.com).

Fotufilm models how a film stock exposes, develops and prints, from each stock's published spectral data. Orchard
doesn't carry it. It loads the engine library from an installed copy of Fotufilm through the C interface in
Fotufilm's `fotufilm.h`, so each look is developed inside this process, on the GPU the engine chooses, without
starting a program per photo. The engine decodes the original itself, RAW files included, so a look starts from the
sensor data rather than the camera's JPEG.

Developed pictures are Display P3 and are saved with that profile. `display-p3.icc` was generated by Fotufilm's
tools/generate-web-color-profiles.py from the public Display P3 definition (Apache-2.0).
"""
from collections import OrderedDict
import ctypes
from ctypes import POINTER, byref, c_char_p, c_double, c_int32, c_size_t, c_uint8, c_uint32, c_void_p
import hashlib
import json
import logging
import os
from pathlib import Path
import sys
import threading

from PIL import Image

NAMES = {'darwin': 'libfotufilm.dylib', 'win32': 'fotufilm.dll'}
LIBRARY_NAME = NAMES.get(sys.platform, 'libfotufilm.so')
# Where an installed Fotufilm keeps its engine, newest layout first. A folder is searched for the library.
CANDIDATES = {
    'darwin': ['/Applications/Fotufilm.app', '~/Applications/Fotufilm.app'],
    'linux': ['~/.local/share/fotufilm', '/opt/fotufilm', '/opt/Fotufilm'],
}
ICC = (Path(__file__).with_name('display-p3.icc')).read_bytes()
FORMATS = ['35mm', '120', '4x5', 'super35', '16mm', 'super8', 'instaxmini', 'instaxsquare', 'instaxwide']
# The engine's own controls that Orchard offers, as (lowest, highest, neutral). The engine checks them too.
CONTROLS = {'exposure': (-5.0, 5.0, 0.0), 'grain': (0.0, 2.0, 1.0), 'push': (-2.0, 2.0, 0.0),
            'expired': (0.0, 30.0, 0.0)}
OK, CANCELLED = 0, 2
RGBA8_DISPLAY_P3 = 0
# Decoded originals kept open, since moving between looks on one photo is the common case.
OPEN_IMAGES = 3
MAX_EDGE = 16384
logger = logging.getLogger(__name__)


class Target(ctypes.Structure):
    _fields_ = [('max_edge', c_uint32), ('format', c_int32), ('pixels', c_void_p), ('row_bytes', c_size_t),
                ('capacity', c_size_t)]


class Info(ctypes.Structure):
    _fields_ = [('width', c_uint32), ('height', c_uint32), ('milliseconds', c_double)]


class FilmUnavailable(RuntimeError):
    pass


def find_library(setting=None) -> Path | None:
    """The engine library named by `setting` or ORCHARD_FOTUFILM, either the file or a folder holding it (an
    extracted AppImage, Fotufilm.app), or else the first installed copy."""
    places = [setting or os.environ.get('ORCHARD_FOTUFILM')] if setting or os.environ.get('ORCHARD_FOTUFILM') else \
        CANDIDATES.get(sys.platform, [])
    for place in places:
        path = Path(place).expanduser()
        if path.is_file():
            return path
        if path.is_dir():
            found = next(path.rglob(LIBRARY_NAME), None)
            if found:
                return found
    return None


def stocks_folder(library: Path) -> Path | None:
    """The film stocks shipped beside the engine: resources/Stocks in the Linux build, Resources/Stocks in the Mac
    app."""
    for parent in library.parents:
        for folder in (parent / 'resources/Stocks', parent / 'Resources/Stocks'):
            if folder.is_dir():
                return folder
        if parent.suffix == '.app':
            break
    return None


def look(params) -> dict:
    """A look from request parameters: a stock, a film format and the controls that differ from neutral. Raises
    ValueError for anything out of range."""
    stock = str(params.get('stock') or '')
    if not stock or len(stock) > 64 or not stock.replace('-', '').replace('_', '').isalnum():
        raise ValueError('Choose a film stock.')
    film_format = params.get('format') or None
    if film_format is not None and film_format not in FORMATS:
        raise ValueError('Choose a film format Fotufilm offers.')
    controls = {}
    for key, (low, high, neutral) in CONTROLS.items():
        value = params.get(key)
        if value in (None, ''):
            continue
        try:
            number = float(value)
        except (TypeError, ValueError):
            raise ValueError(f'{key.capitalize()} must be a number.') from None
        if not low <= number <= high:
            raise ValueError(f'{key.capitalize()} must be between {low:g} and {high:g}.')
        if number != neutral:
            controls[key] = number
    return {'stock': stock, 'format': film_format, 'controls': controls}


def look_key(chosen: dict, edge: int, engine: str) -> str:
    """A name for one look developed at one size by one engine build, for the cache."""
    text = json.dumps({**chosen, 'edge': edge, 'engine': engine}, sort_keys=True)
    return hashlib.sha256(text.encode()).hexdigest()[:20]


class Film:
    """One Fotufilm engine for the app, loaded on first use. Renders on one engine run one at a time."""

    def __init__(self, setting=None):
        self.setting = setting
        self._engine = None
        self._lib = None
        self._describe = None
        self._error = None
        self._lock = threading.Lock()
        self._images = OrderedDict()

    def status(self) -> dict:
        try:
            self._load()
        except FilmUnavailable as error:
            return {'available': False, 'reason': str(error)}
        return {'available': True, 'backend': self._describe.get('backend'), 'engine': self.version,
                'stocks': [{'id': stock['id'], 'name': stock.get('name', stock['id']),
                            'format': stock.get('nativeFormat')} for stock in self._describe.get('stocks', [])],
                'formats': FORMATS,
                'controls': {key: {'min': low, 'max': high, 'neutral': neutral}
                             for key, (low, high, neutral) in CONTROLS.items()}}

    @property
    def version(self) -> str:
        """The engine build, from its library file, so a new Fotufilm develops looks afresh."""
        self._load()
        status = self._path.stat()
        return f'{self._describe.get("apiVersion")}-{status.st_size}-{status.st_mtime_ns}'

    def stocks(self) -> set[str]:
        self._load()
        return {stock['id'] for stock in self._describe.get('stocks', [])}

    def _load(self):
        with self._lock:
            if self._engine:
                return
            if self._error:
                raise FilmUnavailable(self._error)
            path = find_library(self.setting)
            if not path:
                self._error = ('Fotufilm is not installed. Install it from https://fotufilm.com, or point '
                               'ORCHARD_FOTUFILM at its engine library.')
                raise FilmUnavailable(self._error)
            stocks = stocks_folder(path)
            if stocks and not os.environ.get('FOTUFILM_STOCKS'):
                # The engine reads its stocks from here; it must be set before the engine starts.
                os.environ['FOTUFILM_STOCKS'] = str(stocks)
            try:
                lib = ctypes.CDLL(str(path))
                self._declare(lib)
                error = c_void_p()
                engine = lib.fotufilm_engine_create(byref(error))
                if not engine:
                    raise OSError(self._take(lib, error) or 'the engine did not start')
                description = lib.fotufilm_engine_describe(engine)
                self._describe = json.loads(ctypes.string_at(description).decode())
                lib.fotufilm_free(description)
            except (OSError, ValueError, AttributeError) as error:
                logger.warning('Fotufilm at %s did not load: %s', path, error)
                self._error = f'Fotufilm could not start: {error}'
                raise FilmUnavailable(self._error) from None
            self._lib, self._engine, self._path = lib, engine, path

    @staticmethod
    def _declare(lib):
        lib.fotufilm_free.argtypes = [c_void_p]
        lib.fotufilm_engine_create.restype = c_void_p
        lib.fotufilm_engine_create.argtypes = [POINTER(c_void_p)]
        lib.fotufilm_engine_describe.restype = c_void_p
        lib.fotufilm_engine_describe.argtypes = [c_void_p]
        lib.fotufilm_image_open.restype = c_void_p
        lib.fotufilm_image_open.argtypes = [c_void_p, c_char_p, POINTER(c_void_p)]
        lib.fotufilm_image_release.argtypes = [c_void_p]
        lib.fotufilm_render_size.argtypes = [c_void_p, c_uint32, POINTER(c_uint32), POINTER(c_uint32)]
        lib.fotufilm_render.restype = c_int32
        lib.fotufilm_render.argtypes = [c_void_p, c_void_p, c_char_p, POINTER(Target), POINTER(Info),
                                        POINTER(c_void_p)]

    @staticmethod
    def _take(lib, error) -> str:
        """The engine's error message, freed."""
        if not error.value:
            return ''
        message = ctypes.string_at(error.value).decode(errors='replace')
        lib.fotufilm_free(error)
        return message

    def _open(self, path: Path):
        """The decoded original, kept for the next few looks. Called with the lock held."""
        status = path.stat()
        key = (str(path), status.st_size, status.st_mtime_ns)
        if key in self._images:
            self._images.move_to_end(key)
            return self._images[key]
        error = c_void_p()
        handle = self._lib.fotufilm_image_open(self._engine, os.fsencode(path), byref(error))
        if not handle:
            raise OSError(self._take(self._lib, error) or 'Fotufilm could not read this file')
        self._images[key] = handle
        while len(self._images) > OPEN_IMAGES:
            self._lib.fotufilm_image_release(self._images.popitem(last=False)[1])
        return handle

    def develop(self, path: Path, chosen: dict, edge: int) -> Image.Image:
        """The photo at `path` developed through a look, fitting `edge` pixels (0 for its own size), as an RGB image
        carrying the Display P3 profile."""
        self._load()
        if chosen['stock'] not in self.stocks():
            raise ValueError('Fotufilm has no film stock by that name.')
        edge = max(0, min(int(edge), MAX_EDGE))
        request = {'handle': 1, 'maxEdge': edge or None, 'edit': {'stock': chosen['stock'], 'params': {}},
                   'profileRequest': {'controls': chosen['controls'],
                                      **({'format': chosen['format']} if chosen['format'] else {})}}
        with self._lock:
            image = self._open(Path(path))
            width, height = c_uint32(), c_uint32()
            self._lib.fotufilm_render_size(image, edge, byref(width), byref(height))
            row = width.value * 4
            pixels = (c_uint8 * (row * height.value))()
            target = Target(edge, RGBA8_DISPLAY_P3, ctypes.cast(pixels, c_void_p), row, len(pixels))
            info, error = Info(), c_void_p()
            result = self._lib.fotufilm_render(self._engine, image, json.dumps(request).encode(), byref(target),
                                               byref(info), byref(error))
            if result != OK:
                raise OSError(self._take(self._lib, error) or ('cancelled' if result == CANCELLED else 'failed'))
        logger.info('Developed %s through %s at %dx%d in %.0f ms', Path(path).name, chosen['stock'], info.width,
                    info.height, info.milliseconds)
        developed = Image.frombuffer('RGBA', (info.width, info.height), pixels, 'raw', 'RGBA', row, 1).convert('RGB')
        developed.info['icc_profile'] = ICC
        return developed


# Sizes a look is developed at for viewing, so nearby window sizes share one cached picture.
VIEW_EDGES = (512, 1024, 2048, 4096)


def view_edge(value) -> int:
    """The developed size for a requested edge: the next of VIEW_EDGES up from it."""
    try:
        wanted = int(value or 2048)
    except ValueError:
        raise ValueError('Use a whole number of pixels.') from None
    return next((edge for edge in VIEW_EDGES if edge >= wanted), VIEW_EDGES[-1])


def save(image: Image.Image, target: Path, quality=90, exif=None):
    """Write a developed picture as a JPEG with its Display P3 profile, whole or not at all."""
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(f'.{target.name}.{threading.get_ident()}.tmp')
    image.save(temporary, 'JPEG', quality=quality, icc_profile=image.info.get('icc_profile'),
               **({'exif': exif} if exif else {}))
    temporary.replace(target)


def upright_exif(exif: Image.Exif | None) -> bytes | None:
    """The original's EXIF for a developed copy, which the engine has already turned upright."""
    if not exif:
        return None
    exif[274] = 1
    return exif.tobytes()


class Export:
    """Develop many photos through one look into a folder, in the background, one at a time."""

    def __init__(self):
        self.state = {'state': 'idle'}
        self._cancel = threading.Event()
        self._thread = None

    def start(self, film: Film, items, chosen: dict, destination: Path, exif_of=None):
        """`items` are (original path, file name) pairs. Existing files are never replaced: a number is added."""
        if self._thread and self._thread.is_alive():
            raise ValueError('An export is already running. Wait for it, or cancel it.')
        # stocks() loads the engine, so a missing Fotufilm fails here rather than in the thread.
        if chosen['stock'] not in film.stocks():
            raise ValueError('Fotufilm has no film stock by that name.')
        destination.mkdir(parents=True, exist_ok=True)
        self._cancel.clear()
        self.state = {'state': 'running', 'done': 0, 'failed': 0, 'total': len(items), 'folder': str(destination)}

        def run():
            for source, name in items:
                if self._cancel.is_set():
                    self.state['state'] = 'cancelled'
                    return
                try:
                    developed = film.develop(source, chosen, 0)
                    stem = Path(name).stem
                    target = destination / f'{stem}.{chosen["stock"]}.jpg'
                    number = 2
                    while target.exists():
                        target = destination / f'{stem}.{chosen["stock"]} {number}.jpg'
                        number += 1
                    save(developed, target, quality=95, exif=upright_exif(exif_of(source) if exif_of else None))
                    self.state['done'] += 1
                except Exception as error:
                    logger.info('Could not develop %s: %s', source, error)
                    self.state['failed'] += 1
            self.state['state'] = 'done'

        self._thread = threading.Thread(target=run, daemon=True)
        self._thread.start()

    def cancel(self):
        self._cancel.set()
